"""OpenCam schema-v1 data integration: real files, no imported JS execution."""
import importlib
import importlib.util
import json
import os
from pathlib import Path
import tempfile
import threading
import unittest
from unittest.mock import patch

from web_export_model import SubtitleSource
from safe_files import SafeDirectory


class OpenCamIntegration(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name).resolve()
        self.folder = self.root / 'course'
        self.folder.mkdir()
        self.data = {'format': 'opencam.web-player', 'schemaVersion': 1,
                     'generator': {'name': 'OpenCam', 'version': '0.3.3'},
                     'entry': 'index.html', 'media': 'media.mp4', 'title': '課程',
                     'chapters': [{'id': 'clip', 'title': '第一章', 'start': 0, 'end': 10}],
                     'subtitles': None}
        (self.folder / 'index.html').write_bytes(b'original player')
        (self.folder / 'media.mp4').write_bytes(b'original video')
        self.write_data()
        self.srt = self.root / 'media.zh-TW.srt'
        self.srt.write_text('1\n00:00:01,250 --> 00:00:02,500\n字幕 <script> & 中文\n', encoding='utf-8')

    def api(self):
        self.assertIsNotNone(importlib.util.find_spec('opencam_integration'),
                             'OpenCam integration is missing')
        return importlib.import_module('opencam_integration')

    def write_data(self):
        (self.folder / 'opencam-player.js').write_text(
            '// Generated by OpenCam — https://github.com/kaoshou/OpenCam\n'
            'window.OpenCamPlayerData = ' + json.dumps(self.data) + ';\n', encoding='utf-8')

    def test_null_subtitles_creates_first_track_without_changing_player_or_chapters(self):
        m = self.api()
        original = (self.folder / 'opencam-player.js').read_bytes()
        result = m.insert_subtitles(self.folder, (SubtitleSource(self.srt, 'zh-tw'),))
        data = m.load_project(self.folder).data
        self.assertEqual(data['chapters'], self.data['chapters'])
        self.assertEqual(data['generator'], self.data['generator'])
        self.assertEqual(data['title'], '課程')
        track = data['subtitles']['tracks'][0]
        self.assertEqual(track['language'], 'zh-TW')
        self.assertEqual(track['cues'], [{'start': 1.25, 'end': 2.5, 'text': '字幕 <script> & 中文'}])
        self.assertEqual(data['subtitles']['defaultTrackId'], track['id'])
        self.assertEqual(result.backup_path.read_bytes(), original)
        self.assertEqual((self.folder / 'index.html').read_bytes(), b'original player')
        self.assertEqual((self.folder / 'media.mp4').read_bytes(), b'original video')

    def test_missing_and_empty_subtitle_structures_are_supported(self):
        m = self.api()
        for subtitles in ('missing', {}, {'tracks': [], 'defaultTrackId': None}):
            with self.subTest(subtitles=subtitles):
                self.data.pop('subtitles', None)
                if subtitles != 'missing': self.data['subtitles'] = subtitles
                self.write_data()
                m.insert_subtitles(self.folder, (SubtitleSource(self.srt, 'zh-TW'),))
                self.assertEqual(len(m.load_project(self.folder).data['subtitles']['tracks']), 1)

    def test_update_matching_language_preserves_other_tracks_ids_and_default(self):
        m = self.api()
        other = {'id': 'english', 'language': 'en', 'label': 'English',
                 'cues': [{'start': 0, 'end': 1, 'text': 'Keep me'}]}
        self.data['subtitles'] = {'defaultTrackId': 'english', 'tracks': [other,
            {'id': 'chinese', 'language': 'zh-TW', 'label': 'Old',
             'cues': [{'start': 0, 'end': 1, 'text': '舊字幕'}]}]}
        self.write_data()
        m.insert_subtitles(self.folder, (SubtitleSource(self.srt, 'ZH-tw'),))
        subtitles = m.load_project(self.folder).data['subtitles']
        self.assertEqual(subtitles['defaultTrackId'], 'english')
        self.assertEqual(subtitles['tracks'][0], other)
        self.assertEqual(subtitles['tracks'][1]['id'], 'chinese')
        self.assertEqual(subtitles['tracks'][1]['cues'][0]['text'], '字幕 <script> & 中文')

    def test_multiple_tracks_and_vtt_can_be_inserted_together(self):
        m = self.api()
        vtt = self.root / 'media.ja.vtt'
        vtt.write_text('WEBVTT\n\n00:01.000 --> 00:03.000\n日本語\n', encoding='utf-8')
        m.insert_subtitles(self.folder, (SubtitleSource(self.srt, 'zh-TW'), SubtitleSource(vtt, 'ja')))
        tracks = m.load_project(self.folder).data['subtitles']['tracks']
        self.assertEqual([t['language'] for t in tracks], ['zh-TW', 'ja'])
        self.assertEqual(tracks[1]['cues'], [{'start': 1.0, 'end': 3.0, 'text': '日本語'}])

    def test_every_update_gets_a_distinct_exact_backup(self):
        m = self.api()
        first_bytes = (self.folder / 'opencam-player.js').read_bytes()
        first = m.insert_subtitles(self.folder, (SubtitleSource(self.srt, 'zh-TW'),))
        second_bytes = (self.folder / 'opencam-player.js').read_bytes()
        second = m.insert_subtitles(self.folder, (SubtitleSource(self.srt, 'en'),))
        self.assertNotEqual(first.backup_path, second.backup_path)
        self.assertEqual(first.backup_path.read_bytes(), first_bytes)
        self.assertEqual(second.backup_path.read_bytes(), second_bytes)

    def test_overlapping_inserts_keep_both_languages_and_backup_each_previous_state(self):
        # Break caught: two windows both merge the same old data, and the
        # second publisher loses the first track without a recoverable backup.
        m = self.api()
        first_at_publish = threading.Event()
        release_first = threading.Event()
        second_done = threading.Event()
        write = SafeDirectory.write_bytes
        results, errors = [], []
        def delay_first(directory, name, data, **kwargs):
            if name == 'opencam-player.js' and threading.current_thread().name == 'first':
                first_at_publish.set()
                if not release_first.wait(3): raise RuntimeError('test publisher timed out')
            return write(directory, name, data, **kwargs)
        def insert(language):
            try: results.append(m.insert_subtitles(self.folder, (SubtitleSource(self.srt, language),)))
            except Exception as error: errors.append(error)
            finally:
                if language == 'en': second_done.set()
        with patch.object(SafeDirectory, 'write_bytes', new=delay_first):
            first = threading.Thread(target=insert, args=('zh-TW',), name='first')
            second = threading.Thread(target=insert, args=('en',), name='second')
            first.start()
            try:
                self.assertTrue(first_at_publish.wait(3))
                second.start()
                # Without serialization the second write finishes while the
                # first waits. With it, the first safely releases after 0.2s.
                second_done.wait(.2)
            finally:
                release_first.set()
                first.join(5)
                if second.ident: second.join(5)
        self.assertFalse(first.is_alive())
        self.assertFalse(second.is_alive())
        self.assertEqual(errors, [])
        self.assertEqual(len(results), 2)
        data = m.load_project(self.folder).data
        self.assertEqual({t['language'] for t in data['subtitles']['tracks']}, {'zh-TW', 'en'})
        prior = [json.loads(r.backup_path.read_text().split('window.OpenCamPlayerData = ', 1)[1].rstrip(';\n'))
                 for r in results]
        self.assertEqual(sorted(len((d.get('subtitles') or {}).get('tracks', [])) for d in prior), [0, 1])

    def test_detects_only_the_associated_mp4_or_project_entry(self):
        m = self.api()
        for path in (self.folder, self.folder / 'media.mp4', self.folder / 'index.html',
                     self.folder / 'opencam-player.js'):
            self.assertEqual(m.detect_opencam_project(path), (True, str(self.folder)))
        unrelated = self.folder / 'other.mp4'
        unrelated.touch()
        self.assertEqual(m.detect_opencam_project(unrelated), (False, None))
        self.assertEqual(m.detect_opencam_project(self.srt), (False, None))

    def test_extra_script_unknown_schema_and_nonfinite_data_are_rejected_without_writes(self):
        m = self.api()
        for bad in ('script', 'schema', 'nan', 'path'):
            with self.subTest(bad=bad):
                self.data['schemaVersion'] = 2 if bad == 'schema' else 1
                self.data['media'] = '../media.mp4' if bad == 'path' else 'media.mp4'
                self.data['chapters'][0]['end'] = float('nan') if bad == 'nan' else 10
                self.write_data()
                if bad == 'script':
                    with (self.folder / 'opencam-player.js').open('a') as f: f.write('alert(1);')
                original = (self.folder / 'opencam-player.js').read_bytes()
                with self.assertRaises(ValueError):
                    m.insert_subtitles(self.folder, (SubtitleSource(self.srt, 'zh-TW'),))
                self.assertEqual((self.folder / 'opencam-player.js').read_bytes(), original)
                self.assertEqual(list(self.folder.glob('*.backup-*.js')), [])

    def test_all_inputs_validated_before_any_write(self):
        m = self.api()
        bad = self.root / 'broken.srt'
        bad.write_text('not subtitles', encoding='utf-8')
        original = (self.folder / 'opencam-player.js').read_bytes()
        for inputs in ((), (SubtitleSource(self.srt, 'zh-TW'), SubtitleSource(bad, 'en')),
                       (SubtitleSource(self.srt, 'zh-TW'), SubtitleSource(self.srt, 'ZH-tw'))):
            with self.assertRaises(ValueError): m.insert_subtitles(self.folder, inputs)
            self.assertEqual((self.folder / 'opencam-player.js').read_bytes(), original)
            self.assertEqual(list(self.folder.glob('*.backup-*.js')), [])

    def test_backup_failure_does_not_replace_original(self):
        m = self.api()
        original = (self.folder / 'opencam-player.js').read_bytes()
        with patch.object(SafeDirectory, 'write_bytes', side_effect=PermissionError('read-only')):
            with self.assertRaises(PermissionError):
                m.insert_subtitles(self.folder, (SubtitleSource(self.srt, 'zh-TW'),))
        self.assertEqual((self.folder / 'opencam-player.js').read_bytes(), original)

    def test_replacement_failure_still_has_exact_recoverable_backup(self):
        m = self.api()
        original = (self.folder / 'opencam-player.js').read_bytes()
        write = SafeDirectory.write_bytes
        def fail_publication(directory, name, data, **kwargs):
            if name == 'opencam-player.js': raise PermissionError('locked')
            return write(directory, name, data, **kwargs)
        with patch.object(SafeDirectory, 'write_bytes', new=fail_publication):
            with self.assertRaises(PermissionError):
                m.insert_subtitles(self.folder, (SubtitleSource(self.srt, 'zh-TW'),))
        self.assertEqual((self.folder / 'opencam-player.js').read_bytes(), original)
        backups = list(self.folder.glob('*.backup-*.js'))
        self.assertEqual(len(backups), 1)
        self.assertEqual(backups[0].read_bytes(), original)

    def test_player_track_limits_and_cue_text_limits_fail_before_backup(self):
        m = self.api()
        tracks = [{'id': f'lang-{i}', 'language': f'x{i}', 'label': str(i),
                   'cues': [{'start': 0, 'end': 1, 'text': 'Keep'}]} for i in range(32)]
        self.data['subtitles'] = {'tracks': tracks, 'defaultTrackId': 'lang-0'}
        self.write_data()
        original = (self.folder / 'opencam-player.js').read_bytes()
        with self.assertRaises(ValueError):
            m.insert_subtitles(self.folder, (SubtitleSource(self.srt, 'zh-TW'),))
        self.assertEqual((self.folder / 'opencam-player.js').read_bytes(), original)
        self.assertEqual(list(self.folder.glob('*.backup-*.js')), [])
        self.data['subtitles'] = None; self.write_data()
        self.srt.write_text('1\n00:00:00,000 --> 00:00:01,000\n' + 'x' * 10001, encoding='utf-8')
        with self.assertRaises(ValueError):
            m.insert_subtitles(self.folder, (SubtitleSource(self.srt, 'zh-TW'),))
        self.assertEqual(list(self.folder.glob('*.backup-*.js')), [])

    @unittest.skipIf(os.name == 'nt', 'POSIX symlinks')
    def test_symlinked_data_media_and_subtitle_are_rejected(self):
        m = self.api()
        for leaf in ('opencam-player.js', 'media.mp4', 'index.html'):
            path = self.folder / leaf
            saved = self.root / leaf
            path.rename(saved)
            path.symlink_to(saved)
            with self.assertRaises(OSError): m.load_project(self.folder)
            self.assertEqual(m.detect_opencam_project(self.folder), (False, None))
            path.unlink(); saved.rename(path)
        link = self.root / 'link.srt'
        link.symlink_to(self.srt)
        with self.assertRaises(OSError):
            m.insert_subtitles(self.folder, (SubtitleSource(link, 'zh-TW'),))
        self.assertEqual(list(self.folder.glob('*.backup-*.js')), [])

    def test_completion_uses_explicit_source_mapping_not_nearby_subtitle(self):
        m = self.api()
        mapping = {str(self.srt): str(self.folder / 'media.mp4')}
        self.assertEqual(m.completed_projects([str(self.srt)], mapping),
                         [(str(self.folder), str(self.srt))])
        self.assertEqual(m.completed_projects([str(self.srt)], {}), [])
        text = self.root / 'media.txt'; text.touch()
        mapping[str(text)] = str(self.folder / 'media.mp4')
        self.assertEqual(m.completed_projects([str(text)], mapping), [])

    def test_automatic_subtitles_include_languages_and_prefer_vtt(self):
        m = self.api()
        for name in ('media.srt', 'media.zh-TW.srt', 'media.zh-TW.vtt', 'media.en.srt', 'unrelated.srt'):
            (self.folder / name).touch()
        tracks = m.subtitle_candidates(self.folder)
        self.assertEqual([(t.path.name, t.language) for t in tracks],
                         [('media.srt', 'und'), ('media.en.srt', 'en'), ('media.zh-TW.vtt', 'zh-TW')])


if __name__ == '__main__': unittest.main()
